/**
 * IdeaBuilder-style automatic connection coordinator.
 *
 * It deliberately delegates all real connection work to ConnectionManager:
 * - geometry validation stays in one place;
 * - hardware generation stays in one place;
 * - machining derivation stays in one place;
 * - BOM continues to read the same Project model.
 *
 * This class only decides "which snapped joint should be connected automatically".
 */
export default class AutoConnectionResolver {
  constructor(editor) {
    this.editor = editor;
    this.enabled = true;
  }

  setEnabled(enabled) {
    this.enabled = enabled !== false;
    return this.enabled;
  }

  /**
   * Convert the latest snap relation of one profile into a recommended connection.
   * Invalid/unsupported snaps are intentionally non-fatal: snapping remains usable
   * even when no connection rule can be applied.
   */
  connectFromSnap(source, options = {}) {
    if (!this.enabled && options.force !== true) return skipped('DISABLED','自动连接已关闭');
    const sourcePart = source?.userData?.part;
    if (sourcePart?.type !== 'PROFILE') return skipped('SOURCE_NOT_PROFILE','自动连接仅处理型材');

    const snap = options.snap || source.userData?.lastSnap;
    if (!snap?.targetProfileId) return skipped('NO_SNAP','当前型材没有有效吸附关系');
    if (!snap.targetFace) return skipped('UNSUPPORTED_SNAP','端点对端点吸附暂不自动创建参数化连接');

    const target = this.editor.getMeshByPartId(snap.targetProfileId);
    if (!target?.userData?.part || target.userData.part.type !== 'PROFILE') {
      return skipped('TARGET_NOT_PROFILE','吸附目标不是可连接型材');
    }

    const endpointConnection = this.findConnectionAtSourceEnd(sourcePart.id,snap.sourceEnd);
    if (endpointConnection) {
      const sameTarget = endpointConnection.targetProfileId === target.userData.part.id
        || endpointConnection.sourceProfileId === target.userData.part.id;
      if (sameTarget) return {status:'EXISTING',connection:endpointConnection,created:false,reason:'当前端部已经存在该连接'};
      if (endpointConnection.autoGenerated && endpointConnection.status === 'INVALID') {
        this.editor.connectionManager.removeConnection(endpointConnection.id);
      } else {
        return skipped('SOURCE_END_OCCUPIED','当前端部已经存在连接；如需换接目标，请先删除原连接');
      }
    }

    const existing = this.findConnectionBetween(sourcePart.id,target.userData.part.id);
    if (existing) return {status:'EXISTING',connection:existing,created:false,reason:'两根型材之间已经存在连接'};

    const ranked = this.editor.connectionManager.recommendDesignFor(source,target,{
      sourceEnd:snap.sourceEnd,
      targetFace:snap.targetFace
    });
    const recommended = ranked.find(item => item.valid);
    if (!recommended) {
      return skipped('NO_VALID_RULE',ranked[0]?.error || '当前吸附关系没有可用连接方式',{ranked});
    }

    const connection = this.editor.connectionManager.createConnection(source,target,{
      sourceEnd:snap.sourceEnd,
      targetFace:snap.targetFace,
      designType:recommended.type
    });
    this.markAutomatic(connection,options.source || 'SNAP',snap,recommended);
    return {
      status:'CREATED',
      created:true,
      connection,
      designType:recommended.type,
      reasons:recommended.reasons || []
    };
  }

  /**
   * Auto-connect a freshly generated DIY profile set.
   *
   * Candidate detection reuses SnapManager geometry without moving any profile.
   * Reciprocal candidates (A->B and B->A) are collapsed into one physical pair;
   * the direction whose target contact lies further inside the target profile is
   * preferred. This makes a beam endpoint connect to a post face rather than
   * treating the post endpoint as the source of the same corner joint.
   */
  connectProfileSet(profileIds = [], options = {}) {
    if (!this.enabled && options.force !== true) return summary([],[],[],[{code:'DISABLED',message:'自动连接已关闭'}]);
    const allowed = new Set((profileIds || []).filter(Boolean));
    if (allowed.size < 2) return summary([],[],[]);

    const proposals = [];
    for (const source of this.editor.meshes || []) {
      const sourceId = source?.userData?.part?.id;
      if (!allowed.has(sourceId) || source.userData.part?.type !== 'PROFILE') continue;
      source.updateMatrixWorld?.(true);
      const candidates = (this.editor.snapManager.collectCandidates(source) || [])
        .filter(candidate => candidate?.snap?.targetFace && allowed.has(candidate.snap.targetProfileId));

      for (const candidate of candidates) {
        const target = this.editor.getMeshByPartId(candidate.snap.targetProfileId);
        if (!target?.userData?.part || target.userData.part.type !== 'PROFILE') continue;
        const ranked = this.editor.connectionManager.recommendDesignFor(source,target,{
          sourceEnd:candidate.snap.sourceEnd,
          targetFace:candidate.snap.targetFace
        });
        const recommended = ranked.find(item => item.valid);
        if (!recommended) continue;
        proposals.push({
          source,
          target,
          snap:candidate.snap,
          candidate,
          recommended,
          targetInteriorMm:this.targetInteriorDistance(target,candidate.targetPoint)
        });
      }
    }

    const byPair = new Map();
    for (const proposal of proposals) {
      const key = pairKey(proposal.source.userData.part.id,proposal.target.userData.part.id);
      const current = byPair.get(key);
      if (!current || compareProposal(proposal,current) < 0) byPair.set(key,proposal);
    }

    const ordered = [...byPair.values()].sort(compareProposal);
    const created = [];
    const existing = [];
    const failures = [];
    const skippedItems = [];
    const usedSourceEnds = new Set();
    for (const connection of this.editor.connectionManager.connections || []) {
      if (allowed.has(connection.sourceProfileId)) usedSourceEnds.add(endpointKey(connection.sourceProfileId,connection.sourceEnd));
    }
    for (const proposal of ordered) {
      const sourceId = proposal.source.userData.part.id;
      const targetId = proposal.target.userData.part.id;
      const sourceEndKey = endpointKey(sourceId,proposal.snap.sourceEnd);
      if (usedSourceEnds.has(sourceEndKey)) {
        skippedItems.push({sourceProfileId:sourceId,targetProfileId:targetId,code:'SOURCE_END_OCCUPIED'});
        continue;
      }
      const old = this.findConnectionBetween(sourceId,targetId);
      if (old) {
        existing.push(old);
        usedSourceEnds.add(sourceEndKey);
        continue;
      }
      try {
        const connection = this.editor.connectionManager.createConnection(proposal.source,proposal.target,{
          sourceEnd:proposal.snap.sourceEnd,
          targetFace:proposal.snap.targetFace,
          designType:proposal.recommended.type
        });
        this.markAutomatic(connection,options.source || 'DIY_TEMPLATE',proposal.snap,proposal.recommended);
        created.push(connection);
        usedSourceEnds.add(sourceEndKey);
      } catch (error) {
        failures.push({sourceProfileId:sourceId,targetProfileId:targetId,message:error?.message || String(error)});
      }
    }
    return summary(created,existing,failures,skippedItems);
  }

  findConnectionBetween(sourceId,targetId) {
    return (this.editor.connectionManager.connections || []).find(connection => {
      return (connection.sourceProfileId === sourceId && connection.targetProfileId === targetId)
        || (connection.sourceProfileId === targetId && connection.targetProfileId === sourceId);
    }) || null;
  }

  findConnectionAtSourceEnd(sourceId,sourceEnd) {
    const normalizedEnd = sourceEnd === 'END' ? 'END' : 'START';
    return (this.editor.connectionManager.connections || []).find(connection => {
      return connection.sourceProfileId === sourceId && connection.sourceEnd === normalizedEnd;
    }) || null;
  }

  targetInteriorDistance(target,worldPoint) {
    if (!target || !worldPoint?.clone) return 0;
    const length = Number(target.userData?.part?.dimensions?.length || 0);
    if (!(length > 0)) return 0;
    target.updateMatrixWorld?.(true);
    const local = target.worldToLocal(worldPoint.clone());
    const station = Number(local.z || 0) + length / 2;
    return Math.max(0,Math.min(station,length - station));
  }

  markAutomatic(connection,source,snap,recommended) {
    connection.autoGenerated = true;
    connection.autoSource = String(source || 'AUTO');
    connection.autoSnapType = snap?.type || null;
    connection.autoRecommendationScore = Number(recommended?.score || 0);
    connection.autoRecommendationReasons = [...(recommended?.reasons || [])];
    connection.autoDesignType = recommended?.type || connection.designType || null;
  }
}

function compareProposal(a,b) {
  // Higher target interior distance first. It resolves reciprocal corner proposals
  // in favour of beam-end -> post-face semantics.
  const interior = Number(b.targetInteriorMm || 0) - Number(a.targetInteriorMm || 0);
  if (Math.abs(interior) > 0.001) return interior;
  const priority = Number(a.candidate?.priority || 0) - Number(b.candidate?.priority || 0);
  if (priority) return priority;
  const score = Number(a.candidate?.score || 0) - Number(b.candidate?.score || 0);
  if (Math.abs(score) > 0.001) return score;
  return Number(b.recommended?.score || 0) - Number(a.recommended?.score || 0);
}

function endpointKey(partId,sourceEnd) {
  return `${partId}|${sourceEnd === 'END' ? 'END' : 'START'}`;
}

function pairKey(a,b) {
  return String(a) < String(b) ? `${a}|${b}` : `${b}|${a}`;
}

function skipped(code,reason,extra = {}) {
  return {status:'SKIPPED',created:false,code,reason,...extra};
}

function summary(created,existing,failures,skippedItems = []) {
  return {
    status:'DONE',
    created,
    existing,
    failures,
    createdCount:created.length,
    existingCount:existing.length,
    failureCount:failures.length,
    skipped:skippedItems,
    skippedCount:skippedItems.length
  };
}
