import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {registerHooks} from 'node:module';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const staticRoot=path.join(root,'src/main/resources/static');
const vendor=path.join(root,'target/classes/static/vendor/three/build/three.module.min.js');
registerHooks({resolve(specifier,context,next){return specifier==='three'?{url:pathToFileURL(vendor).href,shortCircuit:true}:next(specifier,context);}});
const THREE=await import('three');
const {default:ProfileDrawTool}=await import('../src/main/resources/static/js/drawing/ProfileDrawTool.js');
const read=relative=>fs.readFileSync(path.join(staticRoot,relative),'utf8');
const editor={parts:[],meshes:[],captures:0,autoConnectionEnabled:false,projectSettings:{collisionToleranceMm:.5}};
let attached=null;
editor.sceneManager={scene:new THREE.Scene(),renderer:{domElement:{style:{}}},snapMarker:{visible:true},transformControls:{detach(){attached=null;},attach(mesh){attached=mesh;}},setMarqueeMode(){},hideSnapFeedback(){}};
editor.historyManager={capture(){editor.captures++;}};
editor.emitStats=()=>{};editor.emitProjectChanged=()=>{};
editor.interferenceFeedbackManager={refresh(){return {active:false};},requestRefresh(){}};
editor.getMeshByPartId=id=>editor.meshes.find(m=>m.userData.part.id===id);
editor.removePartByIdSilently=id=>{editor.parts=editor.parts.filter(p=>p.id!==id);editor.meshes=editor.meshes.filter(m=>m.userData.part.id!==id);};
editor.addProfileBetweenPoints=(id,start,end)=>{
  const part={id:'P'+editor.parts.length,type:'PROFILE',dimensions:{length:start.distanceTo(end),sectionSize:[30,30]},profilePath:{type:'LINE',length:start.distanceTo(end)},position:{x:0,y:15,z:0},rotation:{x:0,y:0,z:0}};
  const mesh=new THREE.Group();mesh.userData.part=part;editor.parts.push(part);editor.meshes.push(mesh);editor.selected=mesh;return mesh;
};
const tool=new ProfileDrawTool(editor);
function candidate(){tool.start={point:new THREE.Vector3(0,15,0)};tool.hover={point:new THREE.Vector3(600,15,0)};}
assert.equal(tool.defaults().continueDrawing,false);
tool.begin('FREE');candidate();tool.updatePreview(tool.hover);
assert.equal(tool.commitLength(600),true);
assert.equal(tool.mode,'OFF','默认完成一根立即退出');
assert.equal(tool.previewGroup,null);assert.equal(editor.sceneManager.snapMarker.visible,false);
assert.equal(editor.sceneManager.renderer.domElement.style.cursor,'');
assert.equal(attached,editor.selected,'完成后恢复所选构件操作');
assert.equal(editor.captures,1);
tool.begin('FREE',{continueDrawing:true});candidate();assert.equal(tool.commitLength(600),true);
assert.equal(tool.mode,'FREE');assert.equal(tool.start,null);
candidate();tool.updatePreview(tool.hover);
const count=editor.parts.length,captures=editor.captures;
assert.equal(tool.cancelStep(),true);assert.equal(tool.mode,'FREE');assert.equal(tool.start,null);
candidate();assert.equal(tool.handleKeyDown({key:'Escape'}),true);
assert.equal(tool.mode,'OFF','一次 Escape 必须结束，不需要先取消段再退出');
assert.equal(editor.parts.length,count);assert.equal(editor.captures,captures,'结束/取消不应删除已提交构件或新增历史');
tool.begin('FREE');assert.equal(tool.handleKeyDown({key:'Enter'}),true);assert.equal(tool.mode,'OFF');
tool.begin('FREE',{continueDrawing:false});candidate();editor.interferenceFeedbackManager.refresh=()=>({active:true});
assert.equal(tool.commitLength(600),true);assert.equal(tool.mode,'OFF','显式FREE干涉落位保留红色，完成后回选择');
assert.equal(editor.parts.length,count+1);assert.equal(editor.captures,captures+1);
tool.stop();
const html=read('index.html'),app=read('js/app.js'),core=read('js/core/Editor.js'),scene=read('js/core/SceneManager.js'),overlay=read('js/ui/ProfileDrawOverlay.js');
assert.ok(!html.includes('workbenchMode')&&!app.includes('setWorkbenchMode')&&!core.includes('workbenchMode'));
for(const label of ['结束绘制','取消当前段','确认这一根','精确连接与配合','更多加工','端部斜切','几何关系'])assert.ok(html.includes(label),label);
assert.ok(html.includes('@click="returnToSelection"'));
assert.ok(html.includes('class="cad-menu toolbar-more"')&&html.includes('aria-label="更多操作"'),'低频工具需按需展开，不挤占主工具条');
assert.ok(app.includes("window.addEventListener('click',handleCadMenuClick,true)"),'菜单只能在 click 后收起，不能在 pointerdown 吞掉操作');
assert.ok(!app.slice(app.indexOf('function handleCadMenuPointerDown'),app.indexOf('function handleCadMenuClick')).includes('queueMicrotask'));
assert.ok(scene.includes('if(event.button!==0)')&&scene.includes('secondaryClickHandler'),'右键不得通过左键提交链');
assert.ok(overlay.includes('event.preventDefault();tool.stop();'),'长度输入聚焦时 Esc 也结束');
console.log(JSON.stringify({ok:true,version:'0.75.25',oneShotDefault:true,explicitRepeat:true,oneEscapeExit:true,cancelKeepsCommitted:true,noModeSplit:true}));
