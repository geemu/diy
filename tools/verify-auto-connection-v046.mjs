import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const __dirname=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(__dirname,'..');
const staticRoot=path.join(root,'src/main/resources/static');
const resolverModule=await import(pathToFileURL(path.join(staticRoot,'js/connection/AutoConnectionResolver.js')).href);
const AutoConnectionResolver=resolverModule.default;

function part(id){return {id,type:'PROFILE',dimensions:{length:100},designProfile:{profileId:'DESIGN-3030',nominal:'3030',series:'30',slotWidth:8,faceClosures:[]},manufacturingProfile:null};}
function point(z=0){return {x:0,y:0,z,clone(){return point(this.z);}};}
function mesh(id,{snap=null,localZ=0}={}){
  return {
    userData:{part:part(id),lastSnap:snap},
    updateMatrixWorld(){},
    worldToLocal(){return {x:0,y:0,z:localZ};}
  };
}
function fakeManager(connections){
  return {
    connections,
    recommendDesignFor(){return [{valid:true,score:83,reasons:['30 系列设计截面匹配'],type:'ANGLE_BRACKET',label:'角码连接'}];},
    createConnection(source,target,options){
      const c={id:`C${connections.length+1}`,sourceProfileId:source.userData.part.id,targetProfileId:target.userData.part.id,sourceEnd:options.sourceEnd,targetFace:options.targetFace,designType:options.designType,manufacturingRuleId:null};
      connections.push(c);return c;
    }
  };
}

// Auto connection creates an abstract design joint; it must not pick a real M6/M8 rule.
{
  const target=mesh('B');
  const source=mesh('A',{snap:{type:'END_TO_SLOT',targetProfileId:'B',sourceEnd:'END',targetFace:'LEFT'}});
  const connections=[];
  const editor={getMeshByPartId(id){return id==='B'?target:source;},connectionManager:fakeManager(connections)};
  const resolver=new AutoConnectionResolver(editor);
  const result=resolver.connectFromSnap(source,{source:'DRAG'});
  assert.equal(result.status,'CREATED');
  assert.equal(connections.length,1);
  assert.equal(connections[0].autoGenerated,true);
  assert.equal(connections[0].autoSource,'DRAG');
  assert.equal(connections[0].autoSnapType,'END_TO_SLOT');
  assert.equal(connections[0].designType,'ANGLE_BRACKET');
  assert.equal(connections[0].manufacturingRuleId,null);
  const duplicate=resolver.connectFromSnap(source,{source:'DRAG'});
  assert.equal(duplicate.status,'EXISTING');
  assert.equal(connections.length,1);
}

// Reciprocal DIY geometry proposals A->B and B->A must collapse to one physical pair.
{
  const a=mesh('A',{localZ:0});
  const b=mesh('B',{localZ:-30});
  const meshes=[a,b];
  const connections=[];
  const candidates=new Map([
    ['A',[{priority:0,score:0,targetPoint:point(0),snap:{type:'END_TO_SLOT',targetProfileId:'B',sourceEnd:'END',targetFace:'LEFT'}}]],
    ['B',[{priority:0,score:0,targetPoint:point(0),snap:{type:'END_TO_SLOT',targetProfileId:'A',sourceEnd:'START',targetFace:'RIGHT'}}]]
  ]);
  const editor={
    meshes,
    getMeshByPartId(id){return meshes.find(item=>item.userData.part.id===id);},
    snapManager:{collectCandidates(source){return candidates.get(source.userData.part.id)||[];}},
    connectionManager:fakeManager(connections)
  };
  a.worldToLocal=()=>({x:0,y:0,z:-50});
  b.worldToLocal=()=>({x:0,y:0,z:-30});
  const resolver=new AutoConnectionResolver(editor);
  const result=resolver.connectProfileSet(['A','B'],{source:'DIY_TEMPLATE'});
  assert.equal(result.createdCount,1);
  assert.equal(connections.length,1);
  assert.equal(connections[0].sourceProfileId,'A');
  assert.equal(connections[0].targetProfileId,'B');
  assert.equal(connections[0].autoSource,'DIY_TEMPLATE');
  assert.equal(connections[0].manufacturingRuleId,null);
}

