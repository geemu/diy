import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

const __dirname=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(__dirname,'..');
const staticRoot=path.join(root,'src/main/resources/static');
const {default:AutoConnectionResolver}=await import(pathToFileURL(path.join(staticRoot,'js/connection/AutoConnectionResolver.js')).href);
const {CURRENT_APP_VERSION,CURRENT_PROJECT_SCHEMA_VERSION}=await import(pathToFileURL(path.join(staticRoot,'js/io/ProjectSchema.js')).href);

function profile(id) {
  return {
    userData:{part:{id,type:'PROFILE',dimensions:{length:100}}},
    updateMatrixWorld(){},
    worldToLocal(){return {x:0,y:0,z:-50};}
  };
}

function point() {
  return {x:0,y:0,z:0,clone(){return point();}};
}

// 用户主动扫描必须可以绕过“新建构件自动连接”开关，但仍只创建设计连接。
{
  const source=profile('P1');
  const target=profile('P2');
  const connections=[];
  const editor={
    meshes:[source,target],
    getMeshByPartId(id){return id==='P1'?source:target;},
    snapManager:{
      collectCandidates(mesh){
        if(mesh!==source)return [];
        return [{priority:0,score:0,targetPoint:point(),snap:{type:'END_TO_FACE',targetProfileId:'P2',sourceEnd:'END',targetFace:'LEFT'}}];
      }
    },
    connectionManager:{
      connections,
      recommendDesignFor(){return [{valid:true,score:80,reasons:['几何匹配'],type:'ANGLE_BRACKET'}];},
      createConnection(a,b,options){
        const connection={id:'C1',sourceProfileId:a.userData.part.id,targetProfileId:b.userData.part.id,sourceEnd:options.sourceEnd,targetFace:options.targetFace,designType:options.designType,manufacturingRuleId:null,status:'VALID'};
        connections.push(connection);
        return connection;
      },
      removeConnection(){}
    }
  };
  const resolver=new AutoConnectionResolver(editor);
  resolver.setEnabled(false);
  const disabled=resolver.connectProfileSet(['P1','P2']);
  assert.equal(disabled.createdCount,0);
  const forced=resolver.connectProfileSet(['P1','P2'],{force:true,source:'MANUAL_SCAN'});
  assert.equal(forced.createdCount,1);
  assert.equal(connections[0].autoGenerated,true);
  assert.equal(connections[0].autoSource,'MANUAL_SCAN');
  assert.equal(connections[0].manufacturingRuleId,null);
}

// 一键清除只能移除仍为纯自动来源的连接，手工和已人工修改的关系必须保留。
{
  const connections=[
    {id:'C-AUTO',autoGenerated:true,status:'VALID'},
    {id:'C-MANUAL',autoGenerated:false,status:'VALID'},
    {id:'C-EDITED',autoGenerated:false,userOverridden:true,status:'INVALID'}
  ];
  const editor={
    connectionManager:{
      connections,
      removeConnection(id){
        const index=connections.findIndex(item=>item.id===id);
        if(index>=0)connections.splice(index,1);
      }
    }
  };
  const resolver=new AutoConnectionResolver(editor);
  assert.deepEqual(resolver.connectionOverview(),{total:3,automatic:1,manual:2,invalid:1});
  const result=resolver.clearGeneratedConnections();
  assert.equal(result.removedCount,1);
  assert.deepEqual(result.removedIds,['C-AUTO']);
  assert.deepEqual(connections.map(item=>item.id),['C-MANUAL','C-EDITED']);
  assert.deepEqual(result.overview,{total:2,automatic:0,manual:2,invalid:1});
}

